type Dict = Record<string, string>

/** `{n}`-style placeholders are replaced from `vars`. A missing key falls back to English, then to the key. */
export function makeText<K extends string>(en: Record<K, string>, hi: Record<K, string>) {
  return (lang: Lang, key: K, vars?: Record<string, string | number>): string => {
    const raw = (lang === "hi" ? (hi as Dict)[key] : undefined) ?? (en as Dict)[key] ?? key
    return vars ? raw.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : raw
  }
}

