const dictionaries: Record<Lang, Record<I18nKey, string>> = { en, hi }

/** Translate a key. A missing Hindi entry falls back to English (and warns in development). */
export function translate(lang: Lang, key: I18nKey): string {
  const text = dictionaries[lang]?.[key]
  if (text !== undefined) return text
  if (process.env.NODE_ENV !== "production") console.warn(`i18n: missing "${key}" for "${lang}"`)
  return en[key]
}

export function isLang(value: unknown): value is Lang {
  return typeof value === "string" && (LANGS as readonly string[]).includes(value)
}

export function loadLang(): Lang {
  try {
    const stored = window.localStorage.getItem(LANG_STORAGE_KEY)
    return isLang(stored) ? stored : "en"
  } catch {
    return "en"
  }
}

export function saveLang(lang: Lang): void {
  try {
    window.localStorage.setItem(LANG_STORAGE_KEY, lang)
  } catch {
    /* storage can be blocked; the choice then lasts for this page view only */
  }
}
